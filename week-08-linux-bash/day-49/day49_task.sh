#!/bin/bash

echo "=== 1. Создание файла secret.txt с правами 600 ==="
# Создаём файл (пустой)
touch secret.txt
# Устанавливаем права 600 (rw-------)
chmod 600 secret.txt

echo "=== 2. Проверка прав ==="
ls -l secret.txt

echo "=== 3. Запуск sleep 120 в фоне ==="
# & в конце отправляет процесс в фон
sleep 120 &
# $! — специальная переменная Bash, хранит PID последнего фонового процесса
SLEEP_PID=$!
echo "Процесс запущен. Его PID: $SLEEP_PID"

echo "=== 4. Список фоновых задач ==="
jobs

echo "=== 5. Поиск PID через ps ==="
# Ищем процесс в списке всех процессов
ps aux | grep "sleep 120" | grep -v grep

echo "=== 6. Убиваем процесс ==="
# Посылаем сигнал на завершение (SIGTERM)
kill $SLEEP_PID
echo "Отправлена команда kill для PID $SLEEP_PID"

# Ждём секунду, чтобы система обработала сигнал
sleep 1

echo "=== 7. Проверка, что процесс убит ==="
# ps -p <PID> возвращает строку, если процесс жив, и пустоту, если мёртв
if ps -p $SLEEP_PID > /dev/null; then
    echo "ОШИБКА: Процесс всё ещё работает!"
else
    echo "УСПЕХ: Процесс $SLEEP_PID успешно завершён."
fi